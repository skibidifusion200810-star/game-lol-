import test from 'node:test';
import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { offlineApi, offlineTick, BROWSER_SAVE_KEY } from './offline.js';
globalThis.crypto=globalThis.crypto||webcrypto;
const storage=new Map();
globalThis.localStorage={getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,String(value)),removeItem:key=>storage.delete(key)};
const post=(path,body,token='')=>offlineApi(path,{method:'POST',body:JSON.stringify(body)},token);
const get=(path,token='')=>offlineApi(path,{},token);
test('Pages game supports account, market, trading, auctions, chat and persistence without backend',async()=>{
 const first=await post('/auth/register',{username:'TraderOne',password:'secretpass123'});
 assert.equal(first.player.balance,100000);
 assert.ok(first.token.startsWith('browser-demo-'));
 assert.ok(!storage.get(BROWSER_SAVE_KEY).includes('secretpass123'));
 await assert.rejects(post('/auth/register',{username:'traderone',password:'otherpass123'}),/already exists/i);
 assert.equal((await post('/auth/login',{username:'TraderOne',password:'secretpass123'})).player.id,first.player.id);
 await assert.rejects(post('/auth/login',{username:'TraderOne',password:'wrong'}),/Incorrect/i);
 assert.equal((await get('/market/prices')).length,7);
 assert.ok((await get('/market/history/graphics-card')).length>=30);
 await assert.rejects(post('/market/trade',{itemId:'graphics-card',side:'buy',quantity:-5},first.token),/Invalid trade/);
 const buy=await post('/market/trade',{itemId:'graphics-card',side:'buy',quantity:2},first.token);
 assert.equal(buy.total,60000);
 assert.equal((await get('/player/overview',first.token)).inventory[0].quantity,2);
 await post('/market/trade',{itemId:'graphics-card',side:'sell',quantity:1},first.token);
 const listing=await post('/auctions',{itemId:'graphics-card',quantity:1,startingBid:200},first.token);
 assert.equal((await get('/player/overview',first.token)).inventory.length,0);
 const second=await post('/auth/register',{username:'TraderTwo',password:'password321'});
 await assert.rejects(post('/auctions/'+listing.id+'/bid',{amount:200},first.token),/own auction/i);
 assert.equal((await post('/auctions/'+listing.id+'/bid',{amount:200},second.token)).ok,true);
 const stored=JSON.parse(storage.get(BROWSER_SAVE_KEY));
 stored.auctions.find(a=>a.id===listing.id).ends_at=Date.now()-1;
 storage.set(BROWSER_SAVE_KEY,JSON.stringify(stored));
 assert.equal((await get('/auctions')).length,0);
 assert.equal((await get('/player/overview',second.token)).inventory[0].quantity,1);
 assert.equal((await get('/leaderboard')).length,2);
 assert.equal((await post('/chat',{message:'Test local chat'},first.token)).username,'TraderOne');
 assert.equal((await get('/chat')).length,1);
 assert.equal((await offlineTick()).prices.length,7);
 assert.equal((await get('/auth/me',first.token)).username,'TraderOne');
});
